"""Render a Google Apps Script that builds the collection forms.

Paste ``collection/create_forms.gs`` into https://script.google.com, run
``createForms``, and it creates one Google Form per language with a linked
response spreadsheet, logging the links. Nothing here talks to Google.

Each form: consent -> respondent code and optional background -> the anchor
sentences -> "which set were you given?" -> that set only -> submit.

Question titles embed the language and FLORES index (``[ml-0123]``). The CSV
export uses titles as column headers, which is how ingest.py maps every answer
back to its sentence without trusting column order.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .select import DEFAULT_MANIFEST, LANGS, load_manifest

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_SCRIPT = ROOT / "collection" / "create_forms.gs"

LANG_NAME = {"ml": "Malayalam", "ta": "Tamil"}

# Titles double as CSV headers; ingest.py imports these, so change them only here.
CONSENT_TITLE = "Consent"
CONSENT_CHOICE = "I am 18 or older and I agree"
CODE_TITLE = "Respondent code"
SET_TITLE = "Set number"
BACKGROUND = {
    "age": ("Age group", ["18-24", "25-34", "35-49", "50+"]),
    "region": ("Which district or city did you grow up in?", None),
    "frequency": ("How often do you type {lang} in English letters (WhatsApp, Instagram, YouTube comments)?",
                  ["Every day", "Every week", "Rarely", "Never"]),
    "device": ("What are you typing this on?", ["Phone", "Computer", "Tablet"]),
    "keyboard": ("Which keyboard are you using?",
                 ["Normal English keyboard", "Keyboard with {lang} suggestions or transliteration", "Other"]),
}


def sentence_title(lang: str, idx: int, native: str) -> str:
    return f"[{lang}-{idx:04d}] {native}"


def _description(lang: str) -> str:
    name = LANG_NAME[lang]
    return (
        f"This is a research study on how people type {name} in English letters "
        f"(like on WhatsApp). You will see {name} sentences and type each one the way "
        "you normally would. There is no correct spelling. It takes about 20-25 minutes.\n\n"
        "What we collect: what you type, the code the organizer gave you, and the "
        "optional background questions. We do not collect your name, email or phone number.\n\n"
        "How it will be used: the typed sentences and background answers will be "
        "published as an open research dataset under the CC BY-SA 4.0 licence, "
        "linked only to your code. You must be 18 or older to take part. "
        "You can stop at any point before submitting."
    )


def _instructions(lang: str) -> str:
    name = LANG_NAME[lang]
    return (
        f"Type each {name} sentence in English letters, the way you would type it to a friend.\n"
        "- Type the same sentence. Do not translate it into English.\n"
        f"- Use a normal English keyboard. Turn off {name} typing or transliteration suggestions.\n"
        "- Do not copy and paste, and do not look up spellings.\n"
        "- Spell words however you usually do. Short forms are fine if you use them.\n"
        "- English words inside the sentence can be typed the way you normally would."
    )


def render(manifest: dict) -> str:
    data = {}
    for lang in LANGS:
        text = manifest["sentences"][lang]
        data[lang] = {
            "title": f"How do you type {LANG_NAME[lang]} in English letters?",
            "description": _description(lang),
            "instructions": _instructions(lang),
            "background": [
                {"title": title.format(lang=LANG_NAME[lang]),
                 "choices": [c.format(lang=LANG_NAME[lang]) for c in choices] if choices else None}
                for title, choices in BACKGROUND.values()
            ],
            "anchors": [sentence_title(lang, i, text[str(i)]) for i in manifest["anchors"]],
            "blocks": [[sentence_title(lang, i, text[str(i)]) for i in block]
                       for block in manifest["blocks"]],
        }
    payload = json.dumps(data, ensure_ascii=False, indent=1)
    return _TEMPLATE.replace("__DATA__", payload).replace(
        "__CONSTANTS__", json.dumps({"consent": CONSENT_TITLE, "agree": CONSENT_CHOICE,
                                     "code": CODE_TITLE, "set": SET_TITLE}))


_TEMPLATE = r"""/**
 * Creates the romanization-collection Google Forms, one per language.
 * Generated by latscript.human.forms from collection/manifest.json. Do not edit
 * question titles by hand: the ingest step matches answers on them.
 *
 * Usage: script.google.com -> New project -> paste this file -> Run createForms.
 * Links to each form and its response sheet are printed in the execution log.
 */
const DATA = __DATA__;
const TITLES = __CONSTANTS__;

function createForms() {
  for (const lang of Object.keys(DATA)) {
    const out = createForm_(lang, DATA[lang]);
    Logger.log(lang + ' form (send this):  ' + out.form.getPublishedUrl());
    Logger.log(lang + ' form (edit):       ' + out.form.getEditUrl());
    Logger.log(lang + ' responses sheet:   ' + out.sheet.getUrl());
  }
}

function createForm_(lang, d) {
  const form = FormApp.create(d.title);
  form.setDescription(d.description)
      .setProgressBar(true)
      .setConfirmationMessage('Thank you! Your responses have been recorded.');

  form.addMultipleChoiceItem()
      .setTitle(TITLES.consent)
      .setHelpText('I have read the description above and agree to take part.')
      .setChoiceValues([TITLES.agree])
      .setRequired(true);
  form.addTextItem()
      .setTitle(TITLES.code)
      .setHelpText('The short code the organizer gave you, e.g. ' + lang.toUpperCase() + '07.')
      .setRequired(true);

  form.addPageBreakItem().setTitle('About you (optional)');
  for (const q of d.background) {
    if (q.choices) {
      form.addMultipleChoiceItem().setTitle(q.title).setChoiceValues(q.choices).setRequired(false);
    } else {
      form.addTextItem().setTitle(q.title).setRequired(false);
    }
  }

  form.addPageBreakItem().setTitle('Part 1').setHelpText(d.instructions);
  for (const title of d.anchors) {
    form.addParagraphTextItem().setTitle(title).setRequired(true);
  }

  form.addPageBreakItem().setTitle('Part 2');
  const chooser = form.addMultipleChoiceItem()
      .setTitle(TITLES.set)
      .setHelpText('Choose the set number the organizer gave you.')
      .setRequired(true);

  // One section per set. A section's navigation is configured on the page
  // break that follows it, so each set's successor sends respondents to submit.
  const pages = [];
  d.blocks.forEach(function (block, b) {
    const page = form.addPageBreakItem()
        .setTitle('Set ' + (b + 1))
        .setHelpText(d.instructions);
    if (b > 0) page.setGoToPage(FormApp.PageNavigationType.SUBMIT);
    pages.push(page);
    for (const title of block) {
      form.addParagraphTextItem().setTitle(title).setRequired(true);
    }
  });
  chooser.setChoices(pages.map(function (page, b) {
    return chooser.createChoice(String(b + 1), page);
  }));

  const sheet = SpreadsheetApp.create(d.title + ' (responses)');
  form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());
  return {form: form, sheet: sheet};
}
"""


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Render the Google Forms Apps Script.")
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ap.add_argument("--out", type=Path, default=DEFAULT_SCRIPT)
    args = ap.parse_args(argv)
    args.out.write_text(render(load_manifest(args.manifest)), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
