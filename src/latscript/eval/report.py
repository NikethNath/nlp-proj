"""Collect every Phase 2 result into docs/phase2_results.md.

    PYTHONPATH=src python -m latscript.eval.report

Only reads results/; rerun it after any evaluation. Gaps are losses (positive
means the model did worse) with 95% paired bootstrap intervals over sentences.
"""
from __future__ import annotations

import json

from .conditions import RESULTS, ROOT

OUT = ROOT / "docs" / "phase2_results.md"


def _load(sub: str) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((RESULTS / sub).glob("*.json"))]


def _num(x: float, d: int) -> str:
    return f"{x:.{d}f}"


def _gap(g: dict, d: int) -> str:
    lo, hi = g["ci"]
    return f"{g['loss']:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]"


def _share(dec: dict, tag: str) -> str:
    total = dec["gaps"]["total"]["loss"]
    if abs(total) < 1e-9:
        return "-"
    return f"{dec['gaps'][f'spelling_{tag}']['loss'] / total:.0%}"


def decomposition_table(entries: list[tuple[str, str, dict]], d: int, unit: str) -> list[str]:
    """entries: (model, lang, decomposition)."""
    lines = [
        f"| Model | Lang | L1 | L2 canonical | L2 lexical | L3 (writer range) | "
        f"Script gap (canonical) | Spelling gap (canonical) | Script gap (lexical) | "
        f"Spelling gap (lexical) | Spelling share (can. / lex.) |",
        "|" + "---|" * 11,
    ]
    for model, lang, dec in entries:
        lv, gp = dec["levels"], dec["gaps"]
        w = dec["l3_writers"]
        lines.append(
            f"| {model} | {lang} | {_num(lv['l1']['score'], d)} | {_num(lv['l2_canonical']['score'], d)} | "
            f"{_num(lv['l2_lexical']['score'], d)} | {_num(lv['l3']['score'], d)} "
            f"({_num(min(w), d)}-{_num(max(w), d)}) | {_gap(gp['script_canonical'], d)} | "
            f"{_gap(gp['spelling_canonical'], d)} | {_gap(gp['script_lexical'], d)} | "
            f"{_gap(gp['spelling_lexical'], d)} | {_share(dec, 'canonical')} / {_share(dec, 'lexical')} |")
    lines.append("")
    lines.append(f"Unit: {unit}. n = {entries[0][2]['n']} sentences per language." if entries else "")
    return lines


def _model(name: str) -> str:
    return name.split("/")[-1]


def main() -> None:
    parts = ["# Phase 2 results", "",
             "Generated by `python -m latscript.eval.report` from `results/`; do not edit by hand. "
             "Methods and interpretation are in [evaluation.md](evaluation.md).", "",
             "Gaps are losses: positive means worse. Script gap = L1 -> L2, spelling gap = "
             "L2 -> L3, against each L2. Brackets are 95% paired bootstrap intervals over sentences. "
             "Spelling share = spelling gap / total L1 -> L3 gap.", ""]

    mt = _load("mt")
    for subset in ("all", "core"):
        rows = [(_model(r["model"]), r["lang"], r) for r in mt if r["subset"] == subset]
        if rows:
            label = "full devtest" if subset == "all" else "core subset (248 sentences of the human collection)"
            parts += [f"## Translation into English, chrF++, {label}", ""]
            parts += decomposition_table(rows, 1, "chrF++ (higher is better)") + [""]
            parts += ["Share of outputs that echo the input instead of translating it "
                      "(normalized edit distance to the source below 0.3):", "",
                      "| Model | Lang | L1 | L2 canonical | L2 lexical | L3 |", "|---|---|---|---|---|---|"]
            for model, lang, r in rows:
                c = r.get("copy_rate", {})
                if c:
                    parts.append(f"| {model} | {lang} | {c['l1']:.1%} | {c['l2_canonical']:.1%} | "
                                 f"{c['l2_lexical']:.1%} | {c['l3']:.1%} |")
            parts.append("")

    ret = _load("retrieval")
    if ret:
        parts += ["## Bitext retrieval to English, top-1 accuracy", ""]
        parts += decomposition_table([(_model(r["encoder"]), r["lang"], r["en_retrieval"]) for r in ret],
                                     3, "top-1 accuracy among all devtest English references") + [""]
        parts += ["Cosine similarity of each condition to the native-script sentence:", "",
                  "| Encoder | Lang | L2 canonical | L2 lexical | L3 (mean of writers) |", "|---|---|---|---|---|"]
        for r in ret:
            c = r["l1_cosine"]
            l3 = sum(c[f"l3_{i}"] for i in range(5)) / 5
            parts.append(f"| {_model(r['encoder'])} | {r['lang']} | {c['l2_canonical']:.3f} | "
                         f"{c['l2_lexical']:.3f} | {l3:.3f} |")
        parts.append("")

    sur = _load("surprisal")
    if sur:
        parts += ["## Language-model surprisal, bits per native word", ""]
        parts += decomposition_table([(_model(r["model"]), r["lang"], r["bits_per_word"]) for r in sur],
                                     1, "total sentence negative log-likelihood in bits / native words "
                                        "(lower is better, so gaps are extra bits)") + [""]

    tok = _load("tokenization")
    if tok:
        parts += ["## Tokenizer fertility, tokens per native word", ""]
        parts += decomposition_table([(_model(r["tokenizer"]), r["lang"], r["fertility"]) for r in tok],
                                     2, "subword tokens per native word (lower is better, so gaps are "
                                        "extra tokens)") + [""]

    cls = _load("classify")
    if cls:
        parts += ["## Offensive-language detection on DravidianCodeMix", "",
                  "Latin-script, in-language test comments, scored as typed and after IndicXlit "
                  "back-transliteration. Diff = typed - native (positive: typed is better).", "",
                  "| Classifier | Lang | n (offensive) | Metric | Typed (Latin) | Back-transliterated | Diff |",
                  "|---|---|---|---|---|---|---|"]
        for r in cls:
            runs = r["seeds"] if r["kind"] == "finetune" else [r]
            for metric in ("macro_f1", "auroc"):
                if metric not in runs[0]:
                    continue
                a = sum(x[metric]["a"]["score"] for x in runs) / len(runs)
                b = sum(x[metric]["b"]["score"] for x in runs) / len(runs)
                if len(runs) == 1:
                    lo, hi = runs[0][metric]["a_minus_b"]["ci"]
                    diff = f"{a - b:+.3f} [{lo:+.3f}, {hi:+.3f}]"
                else:
                    diffs = [x[metric]["a"]["score"] - x[metric]["b"]["score"] for x in runs]
                    diff = f"{a - b:+.3f} (seeds {min(diffs):+.3f} to {max(diffs):+.3f})"
                kind = "fine-tuned" if r["kind"] == "finetune" else "zero-shot"
                parts.append(f"| {_model(r['model'])} ({kind}) | {r['lang']} | {r['n']} ({r['offensive']}) | "
                             f"{metric} | {a:.3f} | {b:.3f} | {diff} |")
        parts.append("")
        parts.append("Fine-tuned rows average over seeds; the range is the per-seed difference.")
        parts.append("")

    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
