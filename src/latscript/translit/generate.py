"""Build the three orthographic conditions from native-script FLORES.

    L1  native script, as published
    L2  canonical romanization - one spelling per word
    L3  naturalistic romanization - k simulated writers, each internally
        consistent, sampled from human spelling distributions

L2 prefers the modal Dakshina spelling and falls back to the rule romanizer,
so it is the spelling a careful typist would produce. L3 is generated by
applying a writer's unit-level habits to that same canonical form, for every
word rather than only out-of-vocabulary ones. Mixing per-word lexicon sampling
with per-writer habits would make in-vocabulary words vary randomly while
unseen words varied consistently, and the resulting L2->L3 gap would partly
measure that inconsistency rather than orthography.

Because a writer's habits are drawn only from conventions a real share of
annotators use, L3 varies less than two humans do (normalised edit distance
~0.08 vs ~0.25). Degradation measured against it is therefore a lower bound on
what naturally typed text would cause.
"""
from __future__ import annotations

import json
import random
from dataclasses import asdict, dataclass
from pathlib import Path

from ..corpora.flores import Segment, load as load_flores
from .lexicon import Lexicon
from .noise import SpellingNoise

DEFAULT_OUT = Path(__file__).resolve().parents[3] / "data" / "derived"


@dataclass
class Conditions:
    """One FLORES sentence rendered at every orthographic level."""

    idx: int
    lang: str
    split: str
    english: str
    l1_native: str
    l2_canonical: str
    l3_writers: list[str]
    lexicon_coverage: float


def build(lang: str, split: str = "devtest", k: int = 5, seed: int = 0,
          limit: int | None = None,
          lexicon: Lexicon | None = None,
          noise: SpellingNoise | None = None) -> list[Conditions]:
    lex = lexicon or Lexicon.load(lang)
    nz = noise or SpellingNoise.learn(lex)

    # Writers are fixed for the whole corpus: writer 3 is the same person on
    # every sentence, which is what makes cross-sentence consistency meaningful.
    writers = [nz.writer(random.Random(seed * 1000 + i)) for i in range(k)]
    rng = random.Random(seed)

    rows: list[Conditions] = []
    for seg in load_flores(lang, split, limit=limit):
        canonical = lex.canonical_sentence(seg.native)
        hit, total = lex.coverage(seg.native)
        rows.append(Conditions(
            idx=seg.idx, lang=lang, split=split, english=seg.english,
            l1_native=seg.native,
            l2_canonical=canonical,
            l3_writers=[_spell_sentence(w, canonical, rng) for w in writers],
            lexicon_coverage=hit / total if total else 0.0,
        ))
    return rows


def _spell_sentence(writer, canonical: str, rng: random.Random) -> str:
    from .lexicon import _TOKEN
    return "".join(
        part if not part or _TOKEN.fullmatch(part) else writer.spell(part, rng)
        for part in _TOKEN.split(canonical)
    )


def write_jsonl(rows: list[Conditions], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(asdict(row), ensure_ascii=False) + "\n")
    return path


def main(langs=("ml", "ta"), splits=("dev", "devtest"), k: int = 5,
         out: Path | None = None) -> None:
    out = out or DEFAULT_OUT
    for lang in langs:
        lex = Lexicon.load(lang)
        nz = SpellingNoise.learn(lex)
        for split in splits:
            rows = build(lang, split, k=k, lexicon=lex, noise=nz)
            path = write_jsonl(rows, out / f"flores_{lang}_{split}.jsonl")
            cov = sum(r.lexicon_coverage for r in rows) / len(rows)
            print(f"  {path.name}: {len(rows)} sentences, k={k}, "
                  f"mean lexicon coverage {cov:.1%}")


if __name__ == "__main__":
    main()
